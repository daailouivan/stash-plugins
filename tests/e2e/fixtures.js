function makeScene(overrides = {}) {
  const id = String(overrides.id || "1");
  const filePath = overrides.filePath || `/data/videos/StudioA/Scene_${id}.mp4`;
  const parts = filePath.split("/");
  const basename = parts[parts.length - 1];
  const defaultFile = {
    id: String(1000 + (parseInt(id, 10) || 1)),
    path: filePath,
    basename,
    size: 104857600,
    duration: 600,
    width: 1920,
    height: 1080,
    frame_rate: 30,
    bit_rate: 5000000,
    video_codec: "h264",
    format: "mp4",
  };
  const files = overrides.files !== undefined
    ? overrides.files
    : [{ ...defaultFile, ...(overrides.fileOverrides || {}) }];

  const base = {
    id,
    title: `Scene Title ${id}`,
    date: "2025-06-15",
    code: `CODE-${id.padStart(3, "0")}`,
    details: `Details for scene ${id}`,
    organized: false,
    rating100: 80,
    play_count: 3,
    o_counter: 1,
    director: "Director One",
    created_at: "2025-06-16T10:00:00Z",
    updated_at: "2025-06-17T12:00:00Z",
    last_played_at: "2025-06-18T14:00:00Z",
    urls: [`https://example.com/scene/${id}`],
    stash_ids: [{ endpoint: "https://stashdb.org/graphql", stash_id: `stash-uuid-${id}` }],
    studio: { id: "st_1", name: "Studio Alpha" },
    performers: [{ id: "p_1", name: "Alice Star" }],
    tags: [{ id: "t_1", name: "HD" }],
    paths: {
      screenshot: `/scene/${id}/screenshot`,
      preview: `/scene/${id}/preview`,
      stream: `/scene/${id}/stream`,
    },
    files,
  };

  const merged = { ...base, ...overrides };
  delete merged.filePath;
  delete merged.fileOverrides;
  return merged;
}

